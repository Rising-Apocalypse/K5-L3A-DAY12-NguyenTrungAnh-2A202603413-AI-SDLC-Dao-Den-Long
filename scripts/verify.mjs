// One-command verification: build, unit/CLI tests, then run every scenario fixture twice and compare bytes.
// Writes docs/proof/verify-latest.md and docs/proof/phase-1.md (generated, never hand-edited). Exit 0 only if
// everything passes.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import { join } from 'node:path';

const PROOF = 'docs/proof/verify-latest.md';
const PHASE_PROOF = 'docs/proof/phase-1.md';
const OUT_DIR = 'out/verify';
const SEED = '1';
const TICKS = '600';

function fail(message) {
  console.error(`\nverify FAILED: ${message}`);
  process.exit(1);
}

function sh(command, args) {
  console.log(`\n$ ${command} ${args.join(' ')}`);
  const r = spawnSync(command, args, { stdio: 'inherit' });
  if (r.status !== 0) fail(`"${command} ${args.join(' ')}" exited with ${r.status ?? r.signal}`);
}

function capture(command, args) {
  const r = spawnSync(command, args, { encoding: 'utf8' });
  return r.status === 0 ? r.stdout.trim() : null;
}

// A failing run must never leave a stale "green" proof behind.
rmSync(PROOF, { force: true });
rmSync(PHASE_PROOF, { force: true });
rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

// 1. build   2. tests
sh('npm', ['run', 'build']);
const vitestJson = join(OUT_DIR, 'vitest.json');
sh('npx', ['vitest', 'run', '--reporter=default', '--reporter=json', `--outputFile.json=${vitestJson}`]);
const tests = JSON.parse(readFileSync(vitestJson, 'utf8'));

// 3. every scenario fixture, twice
const rows = [];
const scenarioNames = readdirSync('tests/scenarios', { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();
if (scenarioNames.length === 0) fail('no scenarios found in tests/scenarios');

for (const name of scenarioNames) {
  const dir = join('tests/scenarios', name);
  const extra = [];
  if (existsSync(join(dir, 'scenario.json'))) extra.push('--scenario', join(dir, 'scenario.json'));
  if (existsSync(join(dir, 'inputs.json'))) extra.push('--inputs', join(dir, 'inputs.json'));

  const outs = [1, 2].map((n) => join(OUT_DIR, `${name}.${n}.jsonl`));
  for (const out of outs) {
    sh(process.execPath, ['dist/headless.js', '--seed', SEED, '--night', '1', '--ticks', TICKS, ...extra, '--out', out]);
  }
  const [a, b] = outs.map((p) => readFileSync(p));
  const lines = a.toString('utf8').trimEnd().split('\n');
  const endLine = lines[lines.length - 1];
  let endOk = false;
  try {
    endOk = JSON.parse(endLine).type === 'end';
  } catch {
    endOk = false;
  }
  const deterministic = a.equals(b);
  const eventCounts = {};
  for (const line of lines) {
    const doc = JSON.parse(line);
    if (doc.type === 'event') eventCounts[doc.name] = (eventCounts[doc.name] ?? 0) + 1;
  }
  rows.push({ name, lines: lines.length, endLine, endOk, deterministic, eventCounts });
  if (!endOk) fail(`${name}: last line is not an end line`);
  if (!deterministic) fail(`${name}: two runs are not byte-identical`);
}

// 4. proof
const hash = capture('git', ['rev-parse', '--short', 'HEAD']);
const dirty = (capture('git', ['status', '--porcelain', '--', '.', ':!docs/proof']) ?? '') !== '';
const commit = hash ? `${hash}${dirty ? ' (dirty: uncommitted changes)' : ' (clean)'}` : 'uncommitted (no commit yet)';
const cpu = os.cpus()[0]?.model ?? 'unknown';

const md = [
  '# Verification report',
  '',
  'Generated by `npm run verify` (scripts/verify.mjs). Do not edit by hand.',
  '',
  `- Commit: ${commit}`,
  `- Node: ${process.version}`,
  `- OS: ${os.type()} ${os.release()} (${os.platform()}/${os.arch()})`,
  `- CPU: ${cpu}`,
  `- Build: \`npm run build\` passed (tsc --noEmit, headless bundle, web bundle)`,
  `- Tests: ${tests.numPassedTests}/${tests.numTotalTests} passed in ${tests.testResults.length} files` +
    ` (${tests.numFailedTests} failed, ${tests.numPendingTests} skipped)`,
  '',
  `Scenario runs: \`--seed ${SEED} --night 1 --ticks ${TICKS}\`, each executed twice and compared byte for byte.`,
  '',
  '| scenario | lines | end line | deterministic |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.lines} | \`${r.endLine}\` | ${r.deterministic ? 'yes' : 'NO'} |`),
  '',
].join('\n');

// 5. Phase 1 proof: every PRD-0 scope item and every Test Contract section -> the tests and scenario fixtures that
// cover it, with the result read from the Vitest report of this very run (nothing here is written by hand except
// which tests belong to which requirement).
const testRuns = tests.testResults.flatMap((file) =>
  file.assertionResults.map((t) => ({
    file: file.name.split('/').pop(),
    group: t.ancestorTitles.join(' > '),
    title: t.title,
    passed: t.status === 'passed',
    key: `${file.name.split('/').pop()} :: ${[...t.ancestorTitles, t.title].join(' > ')}`,
  })),
);
const scenarioRow = (name) => rows.find((r) => r.name === name);

const REQUIREMENTS = [
  { id: 'PRD-1', text: 'One level, Night 1 (Đảo Bến), round island, 5 Great Lanterns',
    tests: [/sim\.test\.ts :: level and scenario building > default level/], scenarios: ['empty-world', 'contract-sample'] },
  { id: 'PRD-2', text: 'Character walks and jumps; 3D camera (camera yaw drives the move direction; the view itself is web only)',
    tests: [/sim\.test\.ts :: (movement|jump and island edge)/, /input\.test\.ts :: /], scenarios: ['walk-north-60'] },
  { id: 'PRD-3', text: 'Motes are scattered on the island and can be picked up (random spawns, drops, capacity)',
    tests: [/rules\.test\.ts :: (pickup|mote spawns)/, /gameplay\.test\.ts :: (pickup|scheduled spawns)/], scenarios: ['pickup-basic', 'pickup-capacity', 'spawn-schedule'] },
  { id: 'PRD-4', text: 'Deposit light into a lantern to light it (partial deposits, nearest lantern, tie by id, scoring)',
    tests: [/rules\.test\.ts :: deposit/, /gameplay\.test\.ts :: deposit/], scenarios: ['deposit-partial', 'deposit-light', 'deposit-nearest-tie'] },
  { id: 'PRD-5', text: 'Shades appear and chase the player (spawn schedule, wander/chase, hits, safe zones, falling)',
    tests: [/rules\.test\.ts :: (shade hits|shade movement|falling)/, /gameplay\.test\.ts :: (shades|safe zones|falling|scheduled spawns)/],
    scenarios: ['shade-chase', 'shade-hit', 'safe-zone-block', 'safe-zone-evict', 'fall-respawn', 'spawn-schedule'] },
  { id: 'PRD-6', text: 'Pulse (glow) repels shades (cost, radius, stun, push, cooldown)',
    tests: [/rules\.test\.ts :: pulse/, /gameplay\.test\.ts :: pulse/], scenarios: ['pulse-stun', 'pulse-insufficient', 'pulse-cooldown'] },
  { id: 'PRD-7', text: 'Win, lose, score (all_lit / dawn / no_flames, bonuses); the HUD itself is web only',
    tests: [/rules\.test\.ts :: ending the night/, /gameplay\.test\.ts :: ending the night/, /gameplay\.test\.ts :: falling/],
    scenarios: ['win-all-lit', 'dawn', 'fall-last-flame'] },
  { id: 'PRD-8', text: 'Can replay after winning or losing (headless: the same seed replays identically; the R key is web only)',
    tests: [/gameplay\.test\.ts :: determinism of the whole game/, /cli\.test\.ts :: determinism/], scenarios: ['determinism'] },
  { id: 'Contract A', text: 'game.contract.json: fixed keys and every tuning value, single source of numbers',
    tests: [/tuning\.test\.ts :: /, /architecture\.test\.ts :: /], scenarios: [] },
  { id: 'Contract B', text: 'Headless CLI: flags, tick model, exit codes (0 / 1 / 2), stops at game end',
    tests: [/sim\.test\.ts :: tick model/, /cli\.test\.ts :: (headless output|error handling)/], scenarios: ['contract-sample'] },
  { id: 'Contract C', text: 'Inputs file: sparse frames, rising edges, camera yaw, normalised move, validation',
    tests: [/input\.test\.ts :: /], scenarios: ['walk-north-60'] },
  { id: 'Contract D', text: 'Scenario file: defaults, replacing lists, lantern patches, no events or points at build',
    tests: [/scenario\.test\.ts :: /, /sim\.test\.ts :: level and scenario building/], scenarios: ['contract-sample', 'empty-world'] },
  { id: 'Contract E', text: 'Output JSONL: snapshot / event / end shapes, 3-decimal coordinates, byte-identical determinism',
    tests: [/cli\.test\.ts :: (headless output|determinism)/, /gameplay\.test\.ts :: determinism of the whole game/, /rng\.test\.ts :: /], scenarios: ['determinism', 'contract-sample'] },
];

let allCovered = true;
const reqRows = REQUIREMENTS.map((req) => {
  const matched = req.tests.map((re) => testRuns.filter((t) => re.test(t.key)));
  const unmatched = matched.some((m) => m.length === 0);
  const all = [...new Set(matched.flat())];
  const failed = all.filter((t) => !t.passed);
  const scenarioBad = req.scenarios.filter((n) => {
    const row = scenarioRow(n);
    return !row || !row.endOk || !row.deterministic;
  });
  const ok = !unmatched && failed.length === 0 && scenarioBad.length === 0;
  if (!ok) allCovered = false;
  const byGroup = new Map();
  for (const t of all) byGroup.set(`${t.file} / ${t.group}`, (byGroup.get(`${t.file} / ${t.group}`) ?? 0) + 1);
  const testCell = [...byGroup].map(([k, n]) => `${k} (${n})`).join('<br>');
  const scenarioCell = req.scenarios.map((n) => `\`${n}\``).join(', ') || '-';
  const result = ok ? 'PASS' : `FAIL${unmatched ? ' (no test found)' : ''}${failed.length ? ` (${failed.length} failed)` : ''}${scenarioBad.length ? ' (scenario)' : ''}`;
  return `| ${req.id} | ${req.text} | ${testCell} | ${scenarioCell} | ${result} |`;
});

const eventCell = (counts) => Object.entries(counts).map(([k, n]) => `${k} x${n}`).join(', ') || '-';
const phase = [
  '# Phase 1 proof: requirements to evidence',
  '',
  'Generated by `npm run verify` (scripts/verify.mjs). Do not edit by hand. Results are read from the Vitest report',
  'and the scenario runs of this run; the script only decides which tests belong to which requirement.',
  '',
  `- Commit: ${commit}`,
  `- Tests: ${tests.numPassedTests}/${tests.numTotalTests} passed`,
  `- Scenario fixtures: ${rows.length}, each run twice (seed ${SEED}, ${TICKS} ticks) and compared byte for byte`,
  '',
  '| requirement | what | tests (file / group, count) | scenario fixtures | result |',
  '|---|---|---|---|---|',
  ...reqRows,
  '',
  `## Events written by each scenario fixture (seed ${SEED}, ${TICKS} ticks)`,
  '',
  '| scenario | events | end line |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${eventCell(r.eventCounts)} | \`${r.endLine}\` |`),
  '',
  'Parts that exist only in the web build (3D camera, HUD, win/lose overlay, R to replay) are not covered by this',
  'table: they are checked by hand, see README.',
  '',
].join('\n');

mkdirSync('docs/proof', { recursive: true });
writeFileSync(PROOF, md);
writeFileSync(PHASE_PROOF, phase);
if (!allCovered) fail(`a requirement in ${PHASE_PROOF} is not fully covered (see the table)`);
console.log(`\nverify OK -> ${PROOF}, ${PHASE_PROOF}`);
