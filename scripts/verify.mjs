const eventCell = (counts) => Object.entries(counts).map(([k, n]) => `${k} x${n}`).join(', ') || '-';

function renderPhaseProof(title, requirements) {
  let allCovered = true;
  const tableRows = requirements.map((req) => {
    const matched = req.tests.map((re) => testRuns.filter((t) => re.test(t.key)));
    const unmatched = matched.some((m) => m.length === 0);
    const all = [...new Set(matched.flat())];
    const failed = all.filter((t) => !t.passed);
    const scenarioBad = req.scenarios.filter((n) => {
      const row = scenarioRow(n);
      return !row || !row.endOk || !row.deterministic;
    });
    const ok = !unmatched && failed.length === 0 && scenarioBad.length === 0;
    if (!ok) allCovered = false;
    const byGroup = new Map();
    for (const t of all) byGroup.set(`${t.file} / ${t.group}`, (byGroup.get(`${t.file} / ${t.group}`) ?? 0) + 1);
    const testCell = [...byGroup].map(([k, n]) => `${k} (${n})`).join('<br>');
    const scenarioCell = req.scenarios.map((n) => `\`${n}\``).join(', ') || '-';
    const result = ok ? 'PASS' : `FAIL${unmatched ? ' (no test found)' : ''}${failed.length ? ` (${failed.length} failed)` : ''}${scenarioBad.length ? ' (scenario)' : ''}`;
    return `| ${req.id} | ${req.text} | ${testCell} | ${scenarioCell} | ${result} |`;
  });

  const content = [
    `# ${title}`,
    '',
    'Generated by `npm run verify` (scripts/verify.mjs). Do not edit by hand. Results are read from the Vitest report',
    'and the scenario runs of this run; the script only decides which tests belong to which requirement.',
    '',
    `- Commit: ${commit}`,
    `- Tests: ${tests.numPassedTests}/${tests.numTotalTests} passed`,
    `- Scenario fixtures: ${rows.length}, each run twice (seed ${SEED}, ${TICKS} ticks) and compared byte for byte`,
    '',
    '| requirement | what | tests (file / group, count) | scenario fixtures | result |',
    '|---|---|---|---|---|',
    ...tableRows,
    '',
    `## Events written by each scenario fixture (seed ${SEED}, ${TICKS} ticks)`,
    '',
    '| scenario | events | end line |',
    '|---|---|---|',
    ...rows.map((r) => `| ${r.name} | ${eventCell(r.eventCounts)} | \`${r.endLine}\` |`),
    '',
    'Parts that exist only in the web build (3D camera, HUD, win/lose overlay, R to replay) are not covered by this',
    'table: they are checked by hand, see README.',
    '',
  ].join('\n');

  return { ok: allCovered, md: content };
}

