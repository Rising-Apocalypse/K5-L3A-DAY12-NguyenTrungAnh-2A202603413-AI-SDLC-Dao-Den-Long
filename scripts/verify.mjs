// One-command verification: build, unit/CLI tests, then run every scenario fixture twice and compare bytes.
// Writes docs/proof/verify-latest.md and docs/proof/phase-1.md, phase-2.md, phase-3.md (generated, never hand-edited). Exit 0 only if
// everything passes.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import { join } from 'node:path';

const PROOF = 'docs/proof/verify-latest.md';
const PHASE_PROOF = 'docs/proof/phase-1.md';
const PHASE2_PROOF = 'docs/proof/phase-2.md';
const PHASE3_PROOF = 'docs/proof/phase-3.md';
const OUT_DIR = 'out/verify';
const SEED = '1';
const TICKS = '600';

function fail(message) {
  console.error(`\nverify FAILED: ${message}`);
  process.exit(1);
}

function sh(command, args) {
  console.log(`\n$ ${command} ${args.join(' ')}`);
  const r = spawnSync(command, args, { stdio: 'inherit' });
  if (r.status !== 0) fail(`"${command} ${args.join(' ')}" exited with ${r.status ?? r.signal}`);
}

function capture(command, args) {
  const r = spawnSync(command, args, { encoding: 'utf8' });
  return r.status === 0 ? r.stdout.trim() : null;
}

// A failing run must never leave a stale "green" proof behind.
rmSync(PROOF, { force: true });
rmSync(PHASE_PROOF, { force: true });
rmSync(PHASE2_PROOF, { force: true });
rmSync(PHASE3_PROOF, { force: true });
rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

// 1. build   2. tests
sh('npm', ['run', 'build']);
const vitestJson = join(OUT_DIR, 'vitest.json');
sh('npx', ['vitest', 'run', '--reporter=default', '--reporter=json', `--outputFile.json=${vitestJson}`]);
const tests = JSON.parse(readFileSync(vitestJson, 'utf8'));

// 3. every scenario fixture, twice
const rows = [];
const scenarioNames = readdirSync('tests/scenarios', { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();
if (scenarioNames.length === 0) fail('no scenarios found in tests/scenarios');

for (const name of scenarioNames) {
  const dir = join('tests/scenarios', name);
  const extra = [];
  if (existsSync(join(dir, 'scenario.json'))) extra.push('--scenario', join(dir, 'scenario.json'));
  if (existsSync(join(dir, 'inputs.json'))) extra.push('--inputs', join(dir, 'inputs.json'));

  const outs = [1, 2].map((n) => join(OUT_DIR, `${name}.${n}.jsonl`));
  for (const out of outs) {
    sh(process.execPath, ['dist/headless.js', '--seed', SEED, '--night', '1', '--ticks', TICKS, ...extra, '--out', out]);
  }
  const [a, b] = outs.map((p) => readFileSync(p));
  const lines = a.toString('utf8').trimEnd().split('\n');
  const endLine = lines[lines.length - 1];
  let endOk = false;
  try {
    endOk = JSON.parse(endLine).type === 'end';
  } catch {
    endOk = false;
  }
  const deterministic = a.equals(b);
  const eventCounts = {};
  for (const line of lines) {
    const doc = JSON.parse(line);
    if (doc.type === 'event') eventCounts[doc.name] = (eventCounts[doc.name] ?? 0) + 1;
  }
  rows.push({ name, lines: lines.length, endLine, endOk, deterministic, eventCounts });
  if (!endOk) fail(`${name}: last line is not an end line`);
  if (!deterministic) fail(`${name}: two runs are not byte-identical`);
}

// 4. proof
const hash = capture('git', ['rev-parse', '--short', 'HEAD']);
const dirty = (capture('git', ['status', '--porcelain', '--', '.', ':!docs/proof']) ?? '') !== '';
const commit = hash ? `${hash}${dirty ? ' (dirty: uncommitted changes)' : ' (clean)'}` : 'uncommitted (no commit yet)';
const cpu = os.cpus()[0]?.model ?? 'unknown';

const md = [
  '# Verification report',
  '',
  'Generated by `npm run verify` (scripts/verify.mjs). Do not edit by hand.',
  '',
  `- Commit: ${commit}`,
  `- Node: ${process.version}`,
  `- OS: ${os.type()} ${os.release()} (${os.platform()}/${os.arch()})`,
  `- CPU: ${cpu}`,
  `- Build: \`npm run build\` passed (tsc --noEmit, headless bundle, web bundle)`,
  `- Tests: ${tests.numPassedTests}/${tests.numTotalTests} passed in ${tests.testResults.length} files` +
    ` (${tests.numFailedTests} failed, ${tests.numPendingTests} skipped)`,
  '',
  `Scenario runs: \`--seed ${SEED} --night 1 --ticks ${TICKS}\`, each executed twice and compared byte for byte.`,
  '',
  '| scenario | lines | end line | deterministic |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.lines} | \`${r.endLine}\` | ${r.deterministic ? 'yes' : 'NO'} |`),
  '',
].join('\n');

